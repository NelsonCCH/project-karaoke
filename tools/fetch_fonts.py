"""Download the looks' web fonts into karaoke/web/look/fonts/ so the remote page needs no internet.

Google Fonts serves each family as unicode-range slices; the browser fetches only the slices a page's text needs,
so the big CJK families cost little at run time. Noto Sans TC is not fetched: the looks fall back to the device's
own CJK sans (Microsoft JhengHei, PingFang TC), which reads the same. Run once:  .venv\\Scripts\\python tools\\fetch_fonts.py"""
import hashlib
import os
import re
import urllib.request

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "karaoke", "web", "look", "fonts")
FAMILIES = ["Audiowide", "Archivo:wght@400;600;800;900", "Fraunces:opsz,wght@9..144,400;9..144,700",
            "Jost:wght@400;500;700", "Poiret+One", "Josefin+Sans:wght@400;600", "Limelight",
            "IBM+Plex+Sans:wght@400;500;700", "Oswald:wght@500;700", "Barlow:wght@400;600", "Anton",
            "Baloo+2:wght@500;700;800", "Noto+Serif+TC:wght@400;700", "Chiron+GoRound+TC:wght@400;700"]
LATIN_ONLY = ("latin", "latin-ext")
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"


def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60).read()


def main():
    os.makedirs(OUT, exist_ok=True)
    url = "https://fonts.googleapis.com/css2?" + "&".join("family=" + f for f in FAMILIES) + "&display=swap"
    css = get(url).decode()
    out, total = [], 0
    # Latin families' faces come after a /* subset */ comment: keep latin + latin-ext. CJK families: keep every
    # face (their ~100 numbered slices carry no comment).
    for subset, face in re.findall(r"(?:/\* ([\w\[\]-]+) \*/\s*)?(@font-face\s*\{[^}]*\})", css):
        fam = re.search(r"font-family:\s*'([^']+)'", face)[1]
        cjk = fam.endswith(" TC")
        if not cjk and subset not in LATIN_ONLY:
            continue
        src = re.search(r"url\((https://[^)]+)\)", face)[1]
        name = re.sub(r"\W+", "-", fam).lower() + "-" + hashlib.md5(src.encode()).hexdigest()[:10] + ".woff2"
        path = os.path.join(OUT, name)
        if not os.path.exists(path):
            with open(path, "wb") as f:
                f.write(get(src))
        total += os.path.getsize(path)
        out.append(face.replace(src, name))
    with open(os.path.join(OUT, "fonts.css"), "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/fetch_fonts.py (Google Fonts, SIL Open Font License). */\n" + "\n".join(out) + "\n")
    print(len(out), "faces,", total // 1024, "KB")


if __name__ == "__main__":
    main()
